const Adhkar = (() => {
  let currentSet = 'morning';
  const counters = new Map();   // index -> remaining repetitions

  function render() {
    const set = ADHKAR[currentSet];
    counters.clear();
    document.getElementById('adhkarNote').textContent = set.note;
    document.getElementById('adhkarList').innerHTML = set.items.map((item, i) => {
      counters.set(i, item.count);
      return `
        <article class="dhikr-card" data-idx="${i}">
          <p class="dhikr-text">${escapeHtml(item.text)}</p>
          <div class="dhikr-foot">
            <span class="dhikr-src">${escapeHtml(item.src)}</span>
            <button class="dhikr-count" data-idx="${i}">${item.count > 1 ? `التكرار: ${item.count}` : 'تم'}</button>
          </div>
        </article>`;
    }).join('');

    document.querySelectorAll('.dhikr-count').forEach(btn => {
      btn.addEventListener('click', () => tick(+btn.dataset.idx, btn));
    });
    document.querySelectorAll('.set-btn').forEach(b =>
      b.classList.toggle('active', b.dataset.set === currentSet));
  }

  function tick(idx, btn) {
    const left = counters.get(idx) - 1;
    counters.set(idx, left);
    const card = document.querySelector(`.dhikr-card[data-idx="${idx}"]`);
    if (left <= 0) {
      btn.textContent = '✔ تم';
      btn.disabled = true;
      card.classList.add('done');
    } else {
      btn.textContent = `باقي: ${left}`;
    }
  }

  function init() {
    document.querySelectorAll('.set-btn').forEach(btn => {
      btn.addEventListener('click', () => { currentSet = btn.dataset.set; render(); });
    });
    render();
  }

  return { init };
})();
